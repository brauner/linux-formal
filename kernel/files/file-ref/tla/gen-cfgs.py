#!/usr/bin/env python3
"""Generate the TLC configurations of FileRef.tla: the green runs with every
protection on, one run per protection with it off, the zone-width witnesses
and the witnesses that the interesting cases are reached at all."""
import pathlib

FIXES = ["FIX_PREEMPT_GUARD", "FIX_PASS_CNT", "FIX_NO_GET_SLOWPATH",
         "FIX_CMPXCHG_DEAD", "FIX_DEAD_MARK", "FIX_RECHECK", "FIX_GET_RCU"]
SAFETY = ["TypeOK", "NoUAF", "NoStale", "Ledger", "DeadMeansNoRefs",
          "OwedRelease", "RightFile", "NoWarn", "FinalClean"]

# the default layout: the owner, two fget-rcu tasks, one holder, two
# objects (one open at the start), two slots
BASE = {
    "Owner": '"O"', "Getters": '{"G1", "G2"}', "Holders": '{"H1"}',
    "EpollTasks": "{}", "Objs": '{"o1"}', "Slots": '{"s1", "s2"}',
    "Live0": '"o1"', "Slot0": '"s1"', "BITS": 6,
    "GetBudget": 2, "HoldBudget": 1, "EpollBudget": 0, "OpenBudget": 2, "DupBudget": 1,
    "CLOSE_PUT": '"put"', "TRACK_HIST": "FALSE",
}
WIT = dict(BASE, TRACK_HIST="TRUE")
EPOLL = dict(BASE, Getters='{"G1"}', EpollTasks='{"E1"}', EpollBudget=2, CLOSE_PUT='"put_close"')
SMALL = dict(BASE, Getters='{"G1"}', GetBudget=1, OpenBudget=1, DupBudget=0)

# name: (layout, fixes off, invariants, properties, expectation)
CONFIGS = {
    "fixed":        (BASE, [], SAFETY, [], "pass"),
    "fixed_close":  (dict(BASE, CLOSE_PUT='"put_close"'), [], SAFETY, [], "pass"),
    "fixed_epoll":  (EPOLL, [], SAFETY, [], "pass"),
    "fixed_live":   (SMALL, [], SAFETY, ["Terminates"], "pass"),
    # a second object: the slot can get a different file, not only a recycled one
    "fixed_two":    (dict(BASE, Objs='{"o1", "o2"}', Getters='{"G1"}'), [], SAFETY, [], "pass"),
    "no_recheck_two": (dict(BASE, Objs='{"o1", "o2"}', Getters='{"G1"}'), ["FIX_RECHECK"], ["RightFile"], [], "violation"),
    "fixed_live_close": (dict(SMALL, CLOSE_PUT='"put_close"'), [], SAFETY, ["Terminates"], "pass"),
    # one protection off at a time
    "no_preempt_guard": (BASE, ["FIX_PREEMPT_GUARD"], ["NoUAF"], [], "violation"),
    "no_pass_cnt":      (BASE, ["FIX_PASS_CNT"], ["NoWarn"], [], "violation"),
    "get_slowpath":     (BASE, ["FIX_NO_GET_SLOWPATH"], ["Ledger", "DeadMeansNoRefs", "NoStale", "NoWarn"], [], "violation"),
    "no_cmpxchg_dead":  (BASE, ["FIX_CMPXCHG_DEAD"], ["OwedRelease"], [], "violation"),
    "no_dead_mark":     (BASE, ["FIX_DEAD_MARK"], ["NoStale", "NoUAF", "DeadMeansNoRefs"], [], "violation"),
    "no_recheck":       (BASE, ["FIX_RECHECK"], ["RightFile"], [], "violation"),
    "no_get_rcu":       (BASE, ["FIX_GET_RCU"], ["NoUAF"], [], "violation"),
    # the same with close(2) on the one-cmpxchg path
    "no_preempt_guard_close": (dict(BASE, CLOSE_PUT='"put_close"'), ["FIX_PREEMPT_GUARD"], ["NoUAF"], [], "violation"),
    "no_cmpxchg_dead_close":  (dict(BASE, CLOSE_PUT='"put_close"'), ["FIX_CMPXCHG_DEAD"], ["OwedRelease"], [], "violation"),
    # the width of the dead zone: with 4 bits DEAD + 1 = NOREF, so two
    # failed gets on a dead file resurrect it; with 5 bits it takes four
    "zone_escape": (dict(BASE, BITS=4, Holders="{}", GetBudget=1, OpenBudget=0, DupBudget=0),
                    [], ["OwedRelease", "DeadMeansNoRefs", "NoStale"], [], "violation"),
    "zone_ok":     (dict(BASE, BITS=5, Holders="{}", GetBudget=1, OpenBudget=0, DupBudget=0),
                    [], SAFETY, [], "pass"),
    # saturation: 16 references fill a 5-bit counter; a failed get at
    # MAXREF wraps it into the saturation zone, the next put wraps it back
    # one too high and the file leaks silently; one get_file() more and
    # get_file() warns, the puts park the count on SATURATED
    "saturation_get": (dict(BASE, BITS=5, Getters='{"G1"}', GetBudget=1, HoldBudget=15, OpenBudget=0, DupBudget=0),
                       [], ["Ledger"], [], "violation"),
    "saturation_inc": (dict(BASE, BITS=5, Getters="{}", HoldBudget=16, OpenBudget=0, DupBudget=0),
                       [], ["NoWarn", "FinalClean"], [], "violation"),
    # witnesses: the cases the green runs cover are reached
    "witness_resurrect":    (WIT, [], ["NoResurrect"], [], "violation"),
    "witness_recycled_get": (WIT, [], ["NoRecycledGet"], [], "violation"),
    "witness_cas_lost":     (WIT, [], ["NoCasLost"], [], "violation"),
    "witness_same_slot":    (WIT, [], ["NoSameSlot"], [], "violation"),
    "witness_get_fail":     (WIT, [], ["NoGetFail"], [], "violation"),
    "witness_pc_fallback":  (dict(WIT, CLOSE_PUT='"put_close"'), [], ["NoPutCloseFallback"], [], "violation"),
    "witness_epi_fail":     (dict(EPOLL, TRACK_HIST="TRUE"), [], ["NoEpiFail"], [], "violation"),
}

here = pathlib.Path(__file__).resolve().parent
for name, (layout, off, invs, props, expect) in CONFIGS.items():
    lines = [f"\\* generated by gen-cfgs.py: FileRef, expected: {expect}",
             "SPECIFICATION Spec", "CONSTANTS"]
    for k, v in layout.items():
        lines.append(f"  {k} = {v}")
    for f in FIXES:
        lines.append(f"  {f} = {'FALSE' if f in off else 'TRUE'}")
    if invs:
        lines.append("INVARIANTS")
        lines += [f"  {i}" for i in invs]
    if props:
        lines.append("PROPERTIES")
        lines += [f"  {p}" for p in props]
    (here / f"{name}.cfg").write_text("\n".join(lines) + "\n")
print(f"{len(CONFIGS)} configurations written")
