#!/usr/bin/env python3
"""Generate the TLC configurations of the shrink_submounts() models of
work.mount.fixes.3: the propagation algebra of kernel/mount/core with
shrink_submounts() as one of three algorithms (SHRINK), on two scripted
layouts and the random layouts of kernel/mount/core."""
import pathlib

FIXES = ["FIX_TRIM_ANCESTORS", "FIX_HANDLE_LOCKED", "FIX_REPARENT_LATE",
         "FIX_FIND_MASTER_STOP", "FIX_TUCK_LOCK", "FIX_PUT_MNT_NS_DISCONNECT",
         "FIX_CLONE_UNBINDABLE", "FIX_SET_GROUP_UNBINDABLE", "FIX_BUSY_VICTIMS"]
SAFETY = ["TypeOK", "AlgebraOK", "Structure", "IteratorsOK", "NsOK", "RefsOK",
          "CoverOK", "SyncUmountNotBusy", "BusyMirrorOK", "DeadUnderDead", "ShrinkCursorOK"]

LAYOUTS = {
    # name: (mount ids, namespace ids, MaxOps, MaxFds)
    "shrinkkres":   (12, 2, 0, 1),
    "shrinkparent": (8, 2, 0, 1),
    "small":        (6, 3, 3, 1),
    "chain":        (10, 3, 3, 1),
    "peers":        (8, 3, 3, 1),
    "locked":       (9, 3, 3, 1),
}

# name: (layout, shrink, walk restart, invariants, expectation, overrides)
# the scripted layouts end with the umount, MaxOps 0
CONFIGS = {}
for lay in ["shrinkkres", "shrinkparent"]:
    for sh in ["gather", "rescan", "walk"]:
        CONFIGS[f"{lay}_{sh}"] = (lay, sh, True, SAFETY, "pass", {})
# the finding: the graveyard's busy checks precede the umounts
CONFIGS["shrinkkres_gather"] = ("shrinkkres", "gather", True, SAFETY,
    "violation: SyncUmountNotBusy, the copy of B on P1 goes first, its cognate on P2 with it, "
    "and R slides to P2@Fo where B's cognate is looked up; B was checked before that", {})
CONFIGS["shrinkkres_witness_shrink"] = ("shrinkkres", "walk", True, ["NoShrink"], "violation", {})
# the walk's cursor when the parent of the shrunk mount goes along
CONFIGS["shrinkparent_walk_norestart"] = ("shrinkparent", "walk", False, ["ShrinkCursorOK"],
    "violation: ShrinkCursorOK, T went with M and the walk reads T's links to ascend", {})
CONFIGS["shrinkparent_witness_parentwent"] = ("shrinkparent", "walk", True, ["NoParentWent"], "violation", {})
# the random layouts of kernel/mount/core with the walk
for lay in ["small", "chain", "peers", "locked"]:
    CONFIGS[f"{lay}_walk"] = (lay, "walk", True, SAFETY, "pass", {})
    CONFIGS[f"{lay}_walk_norestart"] = (lay, "walk", False, SAFETY, "pass or violation: ShrinkCursorOK", {})
    CONFIGS[f"{lay}_rescan"] = (lay, "rescan", True, SAFETY, "pass", {})
    CONFIGS[f"{lay}_gather"] = (lay, "gather", True, SAFETY, "pass or violation: SyncUmountNotBusy", {})
CONFIGS["small_witness_shrink"] = ("small", "walk", True, ["NoShrink"], "violation", {})

def cfg_text(name, layout, shrink, restart, invs, expect, over):
    ids, nss, ops, fds = LAYOUTS[layout]
    ops = over.get("ops", ops)
    lines = [f"\\* generated by gen-cfgs.py: layout {layout}, expected: {expect}",
             "SPECIFICATION Spec", "CONSTANTS",
             f"  MntIds = {{{', '.join(str(i) for i in range(1, ids + 1))}}}",
             f"  NsIds = {{{', '.join(str(i) for i in range(1, nss + 1))}}}",
             "  Sbs <- SbsDef", "  Dentries <- DentriesDef", "  DSb <- DSbDef",
             "  DParent <- DParentDef", "  SbRoot <- SbRootDef", "  Procs <- ProcsDef",
             "  ProcUser <- ProcUserDef", '  InitSb = "N"', '  RootSb = "R"',
             "  MountSbs <- MountSbsDef", f"  MaxOps = {ops}", f"  MaxFds = {fds}",
             "  Prelude <- PreludeDef"]
    lines += [f"  {f} = TRUE" for f in FIXES]
    lines += ["  CHECK_DOC = FALSE", "  FAILS = 0", f'  SHRINK = "{shrink}"',
              f"  FIX_WALK_RESTART = {'TRUE' if restart else 'FALSE'}", "INVARIANTS"]
    lines += [f"  {i}" for i in invs]
    return "\n".join(lines) + "\n"

here = pathlib.Path(__file__).resolve().parent
for name, (layout, shrink, restart, invs, expect, over) in CONFIGS.items():
    (here / f"{name}.cfg").write_text(cfg_text(name, layout, shrink, restart, invs, expect, over))
print(f"{len(CONFIGS)} configurations")
