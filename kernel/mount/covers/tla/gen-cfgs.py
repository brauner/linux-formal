#!/usr/bin/env python3
"""Generate the TLC configurations of MntCover: the covers mainline leaves
behind on unmounted parents since "namespace: rework connected mounts"."""
import pathlib

LAYOUTS = {
    # name: (mounts, dentries, directory dentries, holders, walkers, locked)
    "lazy":  (["R", "P", "C", "F"], ["dP", "dC", "dF"], ["dP", "dC"], ["H"], ["W1", "W2"], {"C"}),
    "rmdir": (["R", "P", "C", "G"], ["dP", "dC", "dG"], ["dP", "dC", "dG"], ["H", "H2"], ["W1", "W2"], set()),
    "ns":    (["R", "P", "C"], ["dP", "dC"], ["dP", "dC"], ["H", "H2"], ["W1", "W2"], {"P"}),
}
SWITCHES = ["FIX_COVER", "MP_PIN", "COVER_FIRST", "PUT_DROPS", "DETACH_DROPS", "RCU_FREE"]
SAFETY = ["TypeOK", "NoBad", "NoReveal", "CoversOK", "MountpointOK", "Reaped"]

# name: (switches off, invariants, expectation, extra locked mounts)
CONFIGS = {}
for lay in LAYOUTS:
    CONFIGS[f"{lay}_fixed"] = ([], SAFETY, "pass", set())
    # without the cover a lookup on the dead parent shows what the child covered
    CONFIGS[f"{lay}_no_cover"] = (["FIX_COVER"], SAFETY,
                                  "violation: NoReveal, the walk lands on the dentry the child covered", set())
    # a cover that does not pin the mountpoint: the last umount_mnt() frees it
    # and clears DCACHE_MOUNTED, so __follow_mount_rcu() never looks
    CONFIGS[f"{lay}_no_pin"] = (["MP_PIN"], SAFETY,
                                "violation: NoReveal or NoBad, DCACHE_MOUNTED is gone with the mountpoint", set())
    # leave_cover() after umount_mnt(): the mountpoint is already freed
    CONFIGS[f"{lay}_cover_late"] = (["COVER_FIRST"], SAFETY,
                                    "violation: NoBad (mp_uaf), the cover pins a freed mountpoint", set())
    # the final put forgets the covers: they and their mountpoints leak
    CONFIGS[f"{lay}_no_put_drop"] = (["PUT_DROPS"], SAFETY,
                                     "violation: CoversOK or Reaped, the covers outlive their parent", set())
    # kfree() instead of kfree_rcu(): a walker dereferences a freed cover
    CONFIGS[f"{lay}_no_rcu_free"] = (["RCU_FREE"], SAFETY,
                                     "violation: NoBad (cover_uaf), the walker reads a freed cover", set())
    # rmdir leaves the covers on the removed dentry to the parent's final put
    CONFIGS[f"{lay}_no_detach_drop"] = (["DETACH_DROPS"], SAFETY,
                                        "pass: the parent's final put drops them later", set())
    CONFIGS[f"{lay}_witness_standin"] = ([], ["NoStandIn"], "violation: NoStandIn, a walk finds knullfs", set())
    CONFIGS[f"{lay}_witness_put_drop"] = ([], ["NoPutDrop"], "violation: NoPutDrop, a final put drops a cover", set())
CONFIGS["lazy_fixed_file_locked"] = ([], SAFETY, "pass", {"F"})
CONFIGS["lazy_witness_file_standin"] = ([], ["NoFileStandIn"], "violation: NoStandIn, knullfs_file for the locked file", {"F"})
CONFIGS["lazy_witness_allowed"] = ([], ["NoAllowedReveal"],
                                   "violation: NoAllowedReveal, the unlocked child's dentry shows after a lazy umount", set())
CONFIGS["ns_witness_allowed"] = ([], ["NoAllowedReveal"],
                                 "violation: NoAllowedReveal, the unlocked child's dentry shows after the namespace died", set())
CONFIGS["lazy_witness_detach_drop"] = ([], ["NoDetachDrop"], "violation: NoDetachDrop, rmdir drops a cover", set())
CONFIGS["rmdir_witness_detach_drop"] = ([], ["NoDetachDrop"], "violation: NoDetachDrop, rmdir drops a cover", set())

here = pathlib.Path(__file__).resolve().parent
for name, (off, invs, expect, extra) in CONFIGS.items():
    lay = name.split("_")[0]
    mnts, dents, dirs, holders, walkers, locked = LAYOUTS[lay]
    q = lambda xs: "{" + ", ".join(f'"{x}"' for x in sorted(xs)) + "}"
    lines = [f"\\* generated by gen-cfgs.py: MntCover, layout {lay}, expected: {expect}",
             "SPECIFICATION Spec", "CONSTANTS",
             f"  Mnts = {q(mnts)}", '  Root = "R"', "  ParentOf <- ParentDef", "  MpOf <- MpDef",
             f"  Dentries = {q(dents)}", f"  DirDentries = {q(dirs)}", f"  Locked = {q(locked | extra)}",
             f"  Holders = {q(holders)}", "  HolderMnt <- HolderDef",
             f"  Walkers = {q(walkers)}", "  WalkFrom <- FromDef", "  WalkAt <- AtDef", "  Ops <- OpsDef"]
    for s in SWITCHES:
        lines.append(f"  {s} = {'FALSE' if s in off else 'TRUE'}")
    lines += ["INVARIANTS"] + [f"  {i}" for i in invs]
    here.joinpath(name + ".cfg").write_text("\n".join(lines) + "\n")
print(f"{len(CONFIGS)} configurations written")
